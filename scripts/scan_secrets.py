#!/usr/bin/env python
"""Secret scanning for the release tree.

A committed credential is the highest-severity finding in the research report, and the
reason it happened is that nothing checked. This scanner is deliberately dependency-free so
it can run in CI, in a pre-commit hook or by hand.

It reports **where** a match is and a redacted fingerprint â€” never the secret itself, so
running it never creates a second copy of the leak in a log file.

Usage::

    python scripts/scan_secrets.py            # scan the release tree
    python scripts/scan_secrets.py --all      # include files normally excluded from release
    python scripts/scan_secrets.py path ...   # scan specific paths

Exit codes: ``0`` clean, ``1`` findings, ``2`` usage error.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Directories that never enter a release and never need scanning (vendored dependencies,
#: generated output, local environments).
EXCLUDED_DIRS = {
    ".git",
    ".hg",
    ".svn",
    ".venv",
    "venv",
    "node_modules",
    "dist_release",  # generated by scripts/build_release.py
    "dist",
    "build",
    "__pycache__",
    ".pytest_cache",
    ".ruff_cache",
    ".mypy_cache",
    ".vscode",
    "manual_scan_output",
    "uploads",
    "_live_check",
    ".scan-cache",
}

#: Files that legitimately hold local configuration and must not be shipped, so they are
#: not part of the scan either (their absence from the release is checked elsewhere).
EXCLUDED_FILES = {".env", "secureconfigai.db", "test_secureconfigai.db"}

#: Extensions that cannot carry a text credential in a reviewable form.
EXCLUDED_SUFFIXES = {
    ".db",
    ".db-journal",
    ".db-wal",
    ".db-shm",
    ".zip",
    ".gz",
    ".png",
    ".jpg",
    ".jpeg",
    ".gif",
    ".ico",
    ".pdf",
    ".woff",
    ".woff2",
    ".ttf",
    ".eot",
    ".pyc",
    ".pyd",
    ".so",
    ".dll",
    ".exe",
    ".bin",
    ".tsbuildinfo",
    ".map",
}

#: Values that are obviously not live credentials. Matching text containing any of these
#: is reported as a placeholder and does not fail the scan.
PLACEHOLDER_HINTS = re.compile(
    r"(?i)(test|dummy|example|fake|placeholder|not-a-real|notreal|not-a-secret|ci-only|"
    r"local-only|sample|changeme|"
    r"change_me|change-me|replace|your[-_ ]?|xxx|\*\*\*|\.\.\.|<[^>]*>|redacted|"
    r"unit-test|integration-test|correcthorse|wrongpass|hunter2|new-password|"
    r"current-password|autocomplete)"
)

#: Test fixtures legitimately contain fake credentials, and a test that asserts "a wrong
#: password is rejected" must contain one. Under these paths the two low-signal patterns
#: are skipped; the high-signal ones (real provider key formats, private keys, cloud
#: tokens) are still enforced, because a real key has no business in a test file either.
TEST_PATH_HINT = re.compile(r"(^|[\\/])tests?[\\/]")
TEST_SKIPPED_KINDS = {"quoted credential assignment", "postgres url with password"}

PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("openai-style key", re.compile(r"\bsk-[A-Za-z0-9_-]{20,}")),
    ("anthropic-style key", re.compile(r"\bsk-ant-[A-Za-z0-9_-]{20,}")),
    ("aws access key id", re.compile(r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b")),
    ("github token", re.compile(r"\bgh[pousr]_[A-Za-z0-9]{30,}")),
    ("slack token", re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{10,}")),
    ("google api key", re.compile(r"\bAIza[0-9A-Za-z_-]{35}\b")),
    ("private key block", re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY-----")),
    ("postgres url with password", re.compile(r"postgresql(?:\+\w+)?://[^\s:/@]+:(?P<secret>[^\s@]{4,})@")),
    (
        "quoted credential assignment",
        re.compile(
            r"(?i)\b(?:api[_-]?key|secret[_-]?key|access[_-]?token|auth[_-]?token|"
            r"client[_-]?secret|password|passwd|jwt[_-]?secret)\b[\"']?\s*[:=]\s*"
            r"[\"'](?P<secret>[^\"'\n]{12,})[\"']"
        ),
    ),
    (
        "env credential assignment",
        # Deliberately case-sensitive: environment keys are upper-case by convention, and a
        # case-insensitive version matches ordinary Python keyword arguments such as
        # ``password_hint=...``, which would make the scan useless through false positives.
        re.compile(
            r"(?m)^[ \t]*(?:export[ \t]+)?(?:[A-Z0-9_]*(?:SECRET|API_KEY|TOKEN|"
            r"PASSWORD|PASSWD|PRIVATE_KEY)[A-Z0-9_]*)[ \t]*=[ \t]*"
            r"(?P<secret>[^\s#'\"]{16,})[ \t]*$"
        ),
    ),
]

#: Guard against scanning a multi-megabyte generated artefact.
MAX_FILE_BYTES = 2 * 1024 * 1024


def iter_files(paths: list[Path], *, include_excluded: bool) -> list[Path]:
    collected: list[Path] = []
    for path in paths:
        if path.is_file():
            collected.append(path)
            continue
        for candidate in sorted(path.rglob("*")):
            if not candidate.is_file():
                continue
            parts = set(candidate.parts)
            if not include_excluded:
                if parts & EXCLUDED_DIRS:
                    continue
                if candidate.name in EXCLUDED_FILES:
                    continue
            if candidate.suffix.lower() in EXCLUDED_SUFFIXES:
                continue
            collected.append(candidate)
    return collected


def fingerprint(value: str) -> str:
    """A stable, non-reversible identifier so a finding can be discussed safely."""
    return hashlib.sha256(value.encode("utf-8", "replace")).hexdigest()[:12]


def redact(value: str) -> str:
    if len(value) <= 8:
        return "*" * len(value)
    return f"{value[:2]}{'*' * 6}{value[-2:]}"


def scan_file(path: Path) -> list[dict[str, object]]:
    try:
        if path.stat().st_size > MAX_FILE_BYTES:
            return []
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []

    findings: list[dict[str, object]] = []
    is_test = bool(TEST_PATH_HINT.search(str(path)))
    for label, pattern in PATTERNS:
        if is_test and label in TEST_SKIPPED_KINDS:
            continue
        for match in pattern.finditer(text):
            matched = match.group(0)
            secret = match.groupdict().get("secret") or matched
            if PLACEHOLDER_HINTS.search(matched):
                continue
            line = text.count("\n", 0, match.start()) + 1
            findings.append(
                {
                    "path": str(path),
                    "line": line,
                    "kind": label,
                    "match": redact(secret),
                    "fingerprint": fingerprint(secret),
                }
            )
    return findings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Scan a tree for committed secrets.")
    parser.add_argument("paths", nargs="*", help="files or directories (default: project root)")
    parser.add_argument("--all", action="store_true", help="also scan files normally excluded from a release")
    args = parser.parse_args(argv)

    targets = [Path(item).resolve() for item in args.paths] or [ROOT]
    files = iter_files(targets, include_excluded=args.all)

    findings: list[dict[str, object]] = []
    for path in files:
        findings.extend(scan_file(path))

    if findings:
        print(f"FAILED: {len(findings)} potential secret(s) in {len(files)} file(s)\n")
        for finding in findings:
            relative = Path(str(finding["path"])).resolve()
            try:
                relative = relative.relative_to(ROOT)
            except ValueError:
                pass
            print(
                f"  {relative}:{finding['line']}  {finding['kind']}  "
                f"value {finding['match']}  sha256[:12]={finding['fingerprint']}"
            )
        print(
            "\nRemove the value, rotate the credential, and rebuild the release from a\n"
            "clean tree. Deleting the line does not revoke a credential that was shipped."
        )
        return 1

    print(f"OK: no credential patterns found in {len(files)} file(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
